#!/bin/bash

# Usage: ./src/run_experiment_8gpu.sh [mode] [seed] [resume]
# This script orchestrates the full LaTense experiment on an 8-GPU node.
# Mode options: "all" (default), "prepare" (baselines + vectors), "eval" (evaluation only)

MODE=${1:-all}
SEED=${2:-42}
RESUME=${3:-false}

if [[ "$RESUME" == "true" || "$RESUME" == "1" || "$RESUME" == "resume" ]]; then
    export LATENSE_RESUME=1
    echo "Resuming from checkpoints..."
fi

# Prevent tokenizer parallelism deadlocks when running many processes
export TOKENIZERS_PARALLELISM=false

# Define the 9 Configurations (Model, Dataset, Threshold)
# Format: "Dataset|Model|Threshold|MaxSamples|VectorSplit|SweepSplit|EvalSplit|EvalLimit|Alpha"
CONFIGS=(
    "openai/gsm8k|meta-llama/Llama-3.1-8B-Instruct|3|1000|train[200:]|train[:200]|test|500|0.3"
    "wics/strategy-qa|meta-llama/Llama-3.1-8B-Instruct|3||test[1200:]|test[1000:1200]|test[:500]|500|0.3"
    "mandarjoshi/trivia_qa|meta-llama/Llama-3.1-8B-Instruct|3|1000|train[200:]|train[:200]|validation|500|0.3"
    "openai/gsm8k|Qwen/Qwen2.5-7B-Instruct|4|1000|train[200:]|train[:200]|test|500|0.3"
    "wics/strategy-qa|Qwen/Qwen2.5-7B-Instruct|3||test[1200:]|test[1000:1200]|test[:500]|500|0.3"
    "mandarjoshi/trivia_qa|Qwen/Qwen2.5-7B-Instruct|3|1000|train[200:]|train[:200]|validation|500|0.3"
    "openai/gsm8k|google/gemma-2-9b-it|4|1000|train[200:]|train[:200]|test|500|0.3"
    "wics/strategy-qa|google/gemma-2-9b-it|3||test[1200:]|test[1000:1200]|test[:500]|500|0.3"
    "mandarjoshi/trivia_qa|google/gemma-2-9b-it|3|1000|train[200:]|train[:200]|validation|500|0.3"
    "openai/gsm8k|google/gemma-2-9b-it|3|1000|train[200:]|train[:200]|test|500|0.3"
)

RESULTS_DIR="./results"
VECTORS_DIR="./vectors"
LOG_DIR="./logs"
mkdir -p "$LOG_DIR"

# Safety check: Ensure we are running from the project root
if [ ! -d "./src" ]; then
    echo "Error: This script must be run from the project root directory (where the 'src' folder is located)."
    exit 1
fi

# Load optimized alphas if available (generated by run_all_sweeps.sh)
if [ -f "./src/best_alphas.sh" ]; then
    source ./src/best_alphas.sh
    echo "Loaded optimized alphas from ./src/best_alphas.sh"
fi

run_task() {
    local CMD_TYPE=$1
    local GPU_ID=$2
    local CONFIG_STR=$3
    
    IFS='|' read -r DATASET MODEL THRESH MAX_SAMPLES VECTOR_SPLIT SWEEP_SPLIT EVAL_SPLIT EVAL_LIMIT ALPHA <<< "$CONFIG_STR"
    
    # create a safe directory name from model/dataset
    local MODEL_SHORT=$(basename "$MODEL")
    local DATA_SHORT=${DATASET//\//_}
    # append threshold to path so T3 and T4 don't overwrite each other

    # Check for override from best_alphas.sh
    local SAFE_DATA=${DATA_SHORT//-/_}
    local SAFE_MODEL=${MODEL_SHORT//-/_}
    SAFE_MODEL=${SAFE_MODEL//./_}
    local VAR_NAME="ALPHA_${SAFE_DATA}_${SAFE_MODEL}_${THRESH}"
    local OPTIMAL_ALPHA=${!VAR_NAME}
    
    if [ ! -z "$OPTIMAL_ALPHA" ]; then
        echo "[GPU $GPU_ID] Overriding Alpha $ALPHA with Optimized Alpha $OPTIMAL_ALPHA"
        ALPHA=$OPTIMAL_ALPHA
    fi

    local VEC_PATH="$VECTORS_DIR/${DATA_SHORT}_${MODEL_SHORT}_thresh${THRESH}_seed${SEED}"

    # define a log file for this specific task
    local LOG_FILE="$LOG_DIR/${CMD_TYPE}_${DATA_SHORT}_${MODEL_SHORT}_seed${SEED}_gpu${GPU_ID}.log"

    echo "[GPU $GPU_ID] Starting $CMD_TYPE for $MODEL on $DATASET (Logs: $LOG_FILE)..."

    # Create a unique results subdirectory for this specific config to prevent overwrites
    local CONFIG_RESULTS_DIR="$RESULTS_DIR/${DATA_SHORT}_${MODEL_SHORT}_thresh${THRESH}"
    mkdir -p "$CONFIG_RESULTS_DIR"

    if [ "$CMD_TYPE" == "BASELINE" ]; then
        # Run CoT and SC sequentially on this GPU
        CUDA_VISIBLE_DEVICES=$GPU_ID ./src/run_baselines.sh "$DATASET" "$MODEL" "$CONFIG_RESULTS_DIR" "greedy_cot" "$EVAL_SPLIT" "$EVAL_LIMIT" > "$LOG_FILE" 2>&1
        CUDA_VISIBLE_DEVICES=$GPU_ID ./src/run_baselines.sh "$DATASET" "$MODEL" "$CONFIG_RESULTS_DIR" "self_consistency" "$EVAL_SPLIT" "$EVAL_LIMIT" >> "$LOG_FILE" 2>&1
    
    elif [ "$CMD_TYPE" == "VECTOR" ]; then
        # Run Vector Pipeline
        # Note: We pass MAX_SAMPLES if it exists
        CUDA_VISIBLE_DEVICES=$GPU_ID ./src/run_vector_pipeline.sh "$DATASET" "$MODEL" 3 "$VEC_PATH" "$THRESH" "$MAX_SAMPLES" "$SEED" "$VECTOR_SPLIT" >> "$LOG_FILE" 2>&1
    
    elif [ "$CMD_TYPE" == "EVAL" ]; then
        # Run LaTense Eval
        # Note: run_parallel_eval expects a list of GPUs, but here we just give it 1 specific GPU
        # to keep the logic simple (1 task per GPU).
        ./src/run_parallel_eval.sh "$DATASET" "$MODEL" "$VEC_PATH" "$CONFIG_RESULTS_DIR" "$GPU_ID" "$EVAL_SPLIT" "$EVAL_LIMIT" "$ALPHA" >> "$LOG_FILE" 2>&1
    
    elif [ "$CMD_TYPE" == "CAA" ]; then
        # Contrastive Activation Addition (Static Baseline)
        # We call main.py directly to ensure flags are passed correctly
        python src/main.py \
            --model_name_or_path "$MODEL" \
            --dataset "$DATASET" \
            --output_dir "$CONFIG_RESULTS_DIR" \
            --split "$EVAL_SPLIT" \
            --max_eval_samples "$EVAL_LIMIT" \
            --generation_mode "latense" \
            --vector_name_template "$VEC_PATH/vector_0.pt" \
            --alpha "$ALPHA" \
            --no_dynamic_scaling \
            --no_similarity_modulation \
            --prompts_to_run "0" \
            >> "$LOG_FILE" 2>&1

    elif [ "$CMD_TYPE" == "RANDOM" ]; then
        # Random Vector Baseline
        python src/main.py \
            --model_name_or_path "$MODEL" \
            --dataset "$DATASET" \
            --output_dir "$CONFIG_RESULTS_DIR" \
            --split "$EVAL_SPLIT" \
            --max_eval_samples "$EVAL_LIMIT" \
            --generation_mode "latense" \
            --vector_name_template "$VEC_PATH/vector_0.pt" \
            --alpha "$ALPHA" \
            --random_vector \
            --prompts_to_run "0" \
            >> "$LOG_FILE" 2>&1
    fi
    
    echo "[GPU $GPU_ID] Finished $CMD_TYPE for $MODEL on $DATASET"
}

# --- PHASE 1: BASELINES ---
if [[ "$MODE" == "all" || "$MODE" == "prepare" || "$MODE" == "baselines" ]]; then
echo "========================================"
echo "PHASE 1: RUNNING BASELINES (CoT & SC)"
echo "========================================"

# Optimized Schedule:
# GPUs 0-3: Heavy GSM8K tasks (Indices 0, 3, 6, 9)
# GPUs 4-5: Medium/Heavy Pairs (StrategyQA + TriviaQA) for Llama/Qwen
# GPUs 6-7: Split Gemma tasks (StrategyQA, TriviaQA) to avoid bottleneck on heavy model

run_task "BASELINE" 0 "${CONFIGS[0]}" &
run_task "BASELINE" 1 "${CONFIGS[3]}" &
run_task "BASELINE" 2 "${CONFIGS[6]}" &
run_task "BASELINE" 3 "${CONFIGS[9]}" &
(run_task "BASELINE" 4 "${CONFIGS[1]}"; run_task "BASELINE" 4 "${CONFIGS[2]}") &
(run_task "BASELINE" 5 "${CONFIGS[4]}"; run_task "BASELINE" 5 "${CONFIGS[5]}") &
run_task "BASELINE" 6 "${CONFIGS[7]}" &
run_task "BASELINE" 7 "${CONFIGS[8]}" &
wait
fi


# --- PHASE 2: VECTOR CREATION ---
if [[ "$MODE" == "all" || "$MODE" == "prepare" || "$MODE" == "vectors" ]]; then
echo "========================================"
echo "PHASE 2: CREATING VECTORS"
echo "========================================"

run_task "VECTOR" 0 "${CONFIGS[0]}" &
run_task "VECTOR" 1 "${CONFIGS[3]}" &
run_task "VECTOR" 2 "${CONFIGS[6]}" &
run_task "VECTOR" 3 "${CONFIGS[9]}" &
(run_task "VECTOR" 4 "${CONFIGS[1]}"; run_task "VECTOR" 4 "${CONFIGS[2]}") &
(run_task "VECTOR" 5 "${CONFIGS[4]}"; run_task "VECTOR" 5 "${CONFIGS[5]}") &
run_task "VECTOR" 6 "${CONFIGS[7]}" &
run_task "VECTOR" 7 "${CONFIGS[8]}" &
wait
fi


# --- PHASE 3: LATENSE EVALUATION ---
if [[ "$MODE" == "all" || "$MODE" == "eval" ]]; then
echo "========================================"
echo "PHASE 3: RUNNING LATENSE EVAL"
echo "========================================"

run_task "EVAL" 0 "${CONFIGS[0]}" &
run_task "EVAL" 1 "${CONFIGS[3]}" &
run_task "EVAL" 2 "${CONFIGS[6]}" &
run_task "EVAL" 3 "${CONFIGS[9]}" &
(run_task "EVAL" 4 "${CONFIGS[1]}"; run_task "EVAL" 4 "${CONFIGS[2]}") &
(run_task "EVAL" 5 "${CONFIGS[4]}"; run_task "EVAL" 5 "${CONFIGS[5]}") &
run_task "EVAL" 6 "${CONFIGS[7]}" &
run_task "EVAL" 7 "${CONFIGS[8]}" &
wait
fi

# --- PHASE 4: CAA BASELINE (Static Steering) ---
if [[ "$MODE" == "caa" ]]; then
echo "========================================"
echo "PHASE 4: RUNNING CAA BASELINE"
echo "========================================"

run_task "CAA" 0 "${CONFIGS[0]}" &
run_task "CAA" 1 "${CONFIGS[3]}" &
run_task "CAA" 2 "${CONFIGS[6]}" &
run_task "CAA" 3 "${CONFIGS[9]}" &
(run_task "CAA" 4 "${CONFIGS[1]}"; run_task "CAA" 4 "${CONFIGS[2]}") &
(run_task "CAA" 5 "${CONFIGS[4]}"; run_task "CAA" 5 "${CONFIGS[5]}") &
run_task "CAA" 6 "${CONFIGS[7]}" &
run_task "CAA" 7 "${CONFIGS[8]}" &
wait
fi

# --- PHASE 5: RANDOM BASELINE (Representative Only) ---
if [[ "$MODE" == "random" ]]; then
echo "========================================"
echo "PHASE 5: RUNNING RANDOM BASELINE (GSM8K Only)"
echo "========================================"
# Only running on GSM8K + Llama (Config 0) to prove the point cheaply
run_task "RANDOM" 0 "${CONFIGS[0]}"
fi

echo "========================================"
echo "ALL EXPERIMENTS COMPLETE"
echo "========================================"